#!/usr/bin/env python3
"""Contract + functional tests for the deterministic manifest union-merge.

Background
==========

``.ai/.workspace_source_manifest.txt`` is a sorted, unique-line file
inventory generated by ``scripts/workspace_init.sh``. Every AI PR that adds
files appends lines to it, so any two concurrently-open sibling PRs merging
into a shared base conflict on adjacent insertions with near-certainty.
Observed on PR #3909 (2026-08-30): three Codex resolver invocations in one
day, each with the manifest as the ONLY conflicted path, each costing ~5
minutes of LLM time plus a full re-review cycle.

``scripts/review_conflict_prepare.sh`` therefore resolves a two-sided
content conflict on the manifest deterministically — the exact 3-way
resolution of a sorted set-of-lines file is pure set algebra,
``(ours ∩ theirs) ∪ (ours − base) ∪ (theirs − base)`` — and, when the
manifest was the only conflicted path, commits the two-parent merge itself
and sets ``CONFLICT_RESOLVED=true`` so
``scripts/review_conflict_resolve.sh`` short-circuits before any model
invocation.

These tests pin the load-bearing pieces of that contract:

1. The union-merge block exists, is kill-switchable via
   ``CONFLICT_MANIFEST_UNION_ENABLED`` (default true), and excludes
   integration-sync branches (``orchestrator/project-*``), whose
   fingerprint-violation expansion can widen the resolver working set
   after the early-commit decision point.
2. The early-commit branch produces the exact ``[ai-merge-resolve]``
   commit message downstream tooling matches on, signals
   ``CONFLICT_RESOLVED=true``, and does NOT clear ``MERGE_CONFLICT`` —
   the ready-to-merge gate must keep treating the run as a resolver run
   so the resolver commit still gets reviewed before merge.
3. The resolver script's short-circuit sits before any model invocation.
4. Functionally: the live snippet extracted from the prepare script,
   run against a real scratch-repo merge conflict, keeps both sides'
   additions, honours either side's deletions, and emits a sorted,
   deduplicated, LC_ALL=C-collated file.
"""

from __future__ import annotations

import importlib.util
import os
import re
import subprocess
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PREPARE = REPO_ROOT / "scripts" / "review_conflict_prepare.sh"
RESOLVE = REPO_ROOT / "scripts" / "review_conflict_resolve.sh"

MANIFEST_PATH = ".ai/.workspace_source_manifest.txt"
MERGE_RESOLVE_COMMIT_MESSAGE = "[ai-merge-resolve] resolve merge conflicts"


def _prepare_text() -> str:
	return PREPARE.read_text(encoding="utf-8")


def _union_block(text: str) -> str:
	"""The union-merge region: from the path constant to the empty-allowlist check."""
	start = text.index('MANIFEST_UNION_PATH=".ai/.workspace_source_manifest.txt"')
	end = text.index("# When the allowlist is empty there is nothing for Codex to", start)
	return text[start:end]


def _shell_function(text: str, name: str) -> str:
	start = text.index(f"{name}() {{")
	end = text.index("\n}\n", start) + len("\n}")
	return text[start:end]


def test_prepare_names_the_manifest_and_kill_switch() -> None:
	text = _prepare_text()
	assert f'MANIFEST_UNION_PATH="{MANIFEST_PATH}"' in text, (
		"prepare script must pin the manifest path constant"
	)
	block = _union_block(text)
	assert 'CONFLICT_MANIFEST_UNION_ENABLED:-true' in block, (
		"union-merge must be gated on CONFLICT_MANIFEST_UNION_ENABLED with a true default"
	)
	workflow_text = (REPO_ROOT / ".github" / "workflows" / "review_autofix.yml").read_text(
		encoding="utf-8"
	)
	prepare_step = workflow_text.split(
		"- name: Prepare merge-conflict resolver prompt and pre-snapshot", 1
	)[1].split("- name: Run Codex resolver, validate, stage, commit", 1)[0]
	assert "CONFLICT_MANIFEST_UNION_ENABLED: ${{ vars.CONFLICT_MANIFEST_UNION_ENABLED || 'true' }}" in prepare_step, (
		"review_autofix.yml must forward the documented kill switch with a true default"
	)
	assert 'bash "${SUPPORT_SCRIPTS_DIR}/review_conflict_prepare.sh"' in prepare_step


