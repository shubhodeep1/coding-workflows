def test_resolver_staging_failure_is_path_specific_and_fatal() -> None:
	text = RESOLVE.read_text(encoding="utf-8")
	function_text = _shell_function(text, "stage_resolver_touched_path_or_fail")
	with tempfile.TemporaryDirectory() as tmp:
		repo = Path(tmp) / "repo"
		repo.mkdir()
		github_env = Path(tmp) / "github.env"
		scratch_git_env = {
			env_name: env_value
			for env_name, env_value in os.environ.items()
			if not env_name.startswith("GIT_") and env_name != "BASH_ENV"
		}
		subprocess.run(["git", "init", "-q", "-b", "main"], cwd=repo, env=scratch_git_env, check=True)
		(repo / "tracked.txt").write_text("content\n", encoding="utf-8")
		script = f"""set -euo pipefail
GITHUB_ENV={github_env!s}
{function_text}
git() {{
	if [ "$1" = "add" ]; then
		return 42
	fi
	command git "$@"
}}
if stage_resolver_touched_path_or_fail tracked.txt; then
	exit 91
fi
"""
		result = subprocess.run(
			["bash", "-c", script], cwd=repo, env=scratch_git_env,
			text=True, capture_output=True,
		)
		assert result.returncode == 0, result.stderr
		assert "Failed to stage conflict resolver path: tracked.txt" in result.stdout
		assert "git exit=42" in result.stdout
		assert github_env.read_text(encoding="utf-8") == "CONFLICT_RESOLVED=false\n"


def test_marker_free_unmerged_index_entry_blocks_commit() -> None:
	text = RESOLVE.read_text(encoding="utf-8")
	function_text = _shell_function(text, "verify_resolver_index_complete_or_fail")
	with tempfile.TemporaryDirectory() as tmp:
		repo = Path(tmp) / "repo"
		repo.mkdir()
		runtime_dir = Path(tmp) / "runtime"
		runtime_dir.mkdir()
		github_env = Path(tmp) / "github.env"
		scratch_git_env = {
			env_name: env_value
			for env_name, env_value in os.environ.items()
			if not env_name.startswith("GIT_") and env_name != "BASH_ENV"
		}

		def git(*args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
			return subprocess.run(
				["git", *args], cwd=repo, env=scratch_git_env, check=check,
				text=True, capture_output=True,
			)

		git("init", "-q", "-b", "main")
		git("config", "user.name", "t")
		git("config", "user.email", "t@t")
		conflicted = repo / "marker-free.txt"
		conflicted.write_text("base\n", encoding="utf-8")
		git("add", "--", "marker-free.txt")
		git("commit", "-qm", "base")
		git("checkout", "-q", "-b", "modified")
		conflicted.write_text("modified without conflict markers\n", encoding="utf-8")
		git("commit", "-am", "modify", "-q")
		git("checkout", "-q", "main")
		git("rm", "-q", "--", "marker-free.txt")
		git("commit", "-qm", "delete")
		before_head = git("rev-parse", "HEAD").stdout.strip()
		merge = git("merge", "--no-commit", "--no-ff", "modified", check=False)
		assert merge.returncode != 0
		assert "<<<<<<<" not in conflicted.read_text(encoding="utf-8")

		script = f"""set -euo pipefail
RUNTIME_DIR={runtime_dir!s}
GITHUB_ENV={github_env!s}
{function_text}
if verify_resolver_index_complete_or_fail; then
	exit 91
fi
"""
		result = subprocess.run(
			["bash", "-c", script], cwd=repo, env=scratch_git_env,
			text=True, capture_output=True,
		)
		assert result.returncode == 0, result.stderr
		assert "Conflict resolver left unmerged Git index entries" in result.stdout
		assert "marker-free.txt" in result.stdout
		assert github_env.read_text(encoding="utf-8") == "CONFLICT_RESOLVED=false\n"
		assert git("rev-parse", "HEAD").stdout.strip() == before_head
		assert git("diff", "--name-only", "--diff-filter=U", "--").stdout.strip() == "marker-free.txt"


def test_union_merge_pipeline_functional() -> None:
	"""Run the live snippet from the prepare script against a real conflict.

	The snippet between the mktemp line and its cleanup only references
	``MANIFEST_UNION_PATH`` and ``_mu_dir``, so it is runnable verbatim
	inside a scratch repository with an in-progress conflicted merge.
	Testing the extracted live text (not a copy) keeps this green only
	while the shipped pipeline itself is correct.
	"""
	text = _prepare_text()
	block = _union_block(text)
	start = block.index('_mu_dir="$(mktemp -d)"')
	end = block.index('rm -rf "${_mu_dir}"', start) + len('rm -rf "${_mu_dir}"')
	snippet = "\n".join(line.strip() for line in block[start:end].splitlines())

	with tempfile.TemporaryDirectory() as tmp:
		repo = Path(tmp) / "repo"
		repo.mkdir()
		scratch_git_env = {
			env_name: env_value
			for env_name, env_value in os.environ.items()
			if not env_name.startswith("GIT_") and env_name != "BASH_ENV"
		}

		def git(*args: str) -> None:
			subprocess.run(
				["git", *args], cwd=repo, check=True,
				env=scratch_git_env,
				stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
			)

		manifest = repo / MANIFEST_PATH
		git("init", "-q", "-b", "main")
		git("config", "user.name", "t")
		git("config", "user.email", "t@t")
		manifest.parent.mkdir(parents=True)
		manifest.write_text("a.py\nb.py\nm.py\nz.py\n", encoding="utf-8")
		git("add", "-A")
		git("commit", "-qm", "base")
		git("checkout", "-q", "-b", "ours")
		manifest.write_text("a.py\nb.py\nc.py\nm.py\nz.py\n", encoding="utf-8")
		git("commit", "-aqm", "ours adds c.py")
		git("checkout", "-q", "main")
		git("checkout", "-q", "-b", "theirs")
		manifest.write_text("a.py\nb.py\nd.py\nz.py\n", encoding="utf-8")
		git("commit", "-aqm", "theirs adds d.py, removes m.py")
		git("checkout", "-q", "ours")
		merge = subprocess.run(
			["git", "merge", "--no-commit", "--no-ff", "theirs"],
			cwd=repo, env=scratch_git_env,
			stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
		)
		assert merge.returncode != 0, "fixture must produce a manifest conflict"

		script = f'set -euo pipefail\nMANIFEST_UNION_PATH="{MANIFEST_PATH}"\n{snippet}\n'
		subprocess.run(["bash", "-c", script], cwd=repo, env=scratch_git_env, check=True)

		got = manifest.read_text(encoding="utf-8")
		assert got == "a.py\nb.py\nc.py\nd.py\nz.py\n", (
			f"union-merge must keep both sides' additions and honour theirs-side "
			f"deletion of m.py; got: {got!r}"
		)


def main() -> int:
	test_funcs = [v for k, v in sorted(globals().items()) if k.startswith("test_")]
	passed = 0
	failed = 0
	for func in test_funcs:
		name = func.__name__
		try:
			func()
			print(f"  PASS  {name}")
			passed += 1
		except Exception as e:
			print(f"  FAIL  {name}: {e}")
			failed += 1
	print(f"\n{passed} passed, {failed} failed, {passed + failed} total")
	return 1 if failed > 0 else 0


